// Rebuild committed offline assets from dependencies pinned in package-lock.json.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const destination = path.join(root, 'demo', 'vendor');
fs.mkdirSync(path.join(destination, 'files'), { recursive: true });
const files = [];
function copy(source, name) {
  fs.copyFileSync(source, path.join(destination, name));
  files.push(name);
}
const ethersRoot = path.join(root, 'node_modules', 'ethers');
copy(path.join(ethersRoot, 'dist', 'ethers.umd.min.js'), 'ethers.umd.min.js');
copy(path.join(ethersRoot, 'LICENSE.md'), 'ethers-LICENSE.md');
const packages = [
  { name: 'be-vietnam-pro', weights: [400, 500, 600, 700, 800] },
  { name: 'jetbrains-mono', weights: [400, 500, 600, 700] }
];
let css = '/* Generated by npm run demo:assets; Latin, Latin Extended and Vietnamese. */\n';
const versions = { ethers: JSON.parse(fs.readFileSync(path.join(ethersRoot, 'package.json'), 'utf8')).version };
for (const { name, weights } of packages) {
  const directory = path.join(root, 'node_modules', '@fontsource', name);
  versions[`@fontsource/${name}`] = JSON.parse(fs.readFileSync(path.join(directory, 'package.json'), 'utf8')).version;
  copy(path.join(directory, 'LICENSE'), `${name}-LICENSE.txt`);
  for (const weight of weights) {
    const source = fs.readFileSync(path.join(directory, `${weight}.css`), 'utf8');
    for (const block of source.matchAll(/@font-face\s*\{[^}]+\}/g)) {
      if (!new RegExp(`${name}-(?:latin|latin-ext|vietnamese)-`).test(block[0])) continue;
      const woff2 = block[0].match(/url\(\.\/files\/([^)]*\.woff2)\)/);
      if (!woff2) throw new Error(`Missing WOFF2: ${name} ${weight}`);
      copy(path.join(directory, 'files', woff2[1]), `files/${woff2[1]}`);
      css += block[0].replace(/src:[^;]+;/, `src: url('./files/${woff2[1]}') format('woff2');`) + '\n';
    }
  }
}
fs.writeFileSync(path.join(destination, 'fonts.css'), css);
files.push('fonts.css');
const hashes = Object.fromEntries(files.sort().map(name => [name,
  crypto.createHash('sha256').update(fs.readFileSync(path.join(destination, name))).digest('hex')
]));
fs.writeFileSync(path.join(destination, 'manifest.json'), JSON.stringify({ versions, sha256: hashes }, null, 2) + '\n');
console.log(`Prepared ${files.length} local assets with licenses and SHA-256 manifest.`);
